/**
 * Очищает текст от эм дэш (длинных тире) и заменяет букву "ё" на "е"
 * согласно техническим требованиям редполитики.
 */
export function sanitizeTypography(text: string): string {
  if (!text) return text;
  return text
    .replace(/ё/g, 'е')
    .replace(/Ё/g, 'Е')
    .replace(/[\u2014\u2013]/g, '-');
}

/**
 * Рекурсивно нормализует все строки в объекте ответа ИИ
 */
export function sanitizeOutputTypography<T>(data: T): T {
  if (typeof data === 'string') {
    return sanitizeTypography(data) as unknown as T;
  }
  if (Array.isArray(data)) {
    return data.map((item) => sanitizeOutputTypography(item)) as unknown as T;
  }
  if (data !== null && typeof data === 'object') {
    const sanitizedObj: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(data)) {
      sanitizedObj[key] = sanitizeOutputTypography(value);
    }
    return sanitizedObj as T;
  }
  return data;
}

/**
 * Формирует итоговый системный промпт для текстового материала
 */
export function buildTextPrompt(sourceText: string, customStyleGuide?: string): string {
  let prompt = EDITORIAL_SYSTEM_PROMPT;

  if (customStyleGuide && customStyleGuide.trim()) {
    prompt += `\n\nДОПОЛНИТЕЛЬНЫЕ ИНСТРУКЦИИ:\n${customStyleGuide.trim()}`;
  }

  prompt += `\n\nВот исходный материал для обработки:\n${sourceText}`;
  return prompt;
}

