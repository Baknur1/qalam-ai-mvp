/**
 * Универсально нормализует markdown-контент:
 * 1. Раскодирует HTML-сущности (&gt; &lt; &quot; &amp;)
 * 2. Разворачивает все уровни экранированных переносов (\\n, \n, \\t) в реальные символы
 * 3. Удаляет случайные обратные слеши (\) на концах строк, перед заголовками и на пустых строках
 * 4. Изолирует Markdown-таблицы пустыми строками сверху и снизу, чтобы парсеры не отсекали следующий текст
 */
export function normalizeMarkdownContent(text: string): string {
  if (!text) return '';
  let str = text;

  // 1. Раскодирование HTML-сущностей
  str = str
    .replace(/&gt;/g, '>')
    .replace(/&lt;/g, '<')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&');

  // 2. Раскрытие экранированных переводов строк и табуляций любой вложенности
  while (/\\+n/g.test(str)) {
    str = str.replace(/\\+n/g, '\n');
  }
  while (/\\+r/g.test(str)) {
    str = str.replace(/\\+r/g, '\r');
  }
  while (/\\+t/g.test(str)) {
    str = str.replace(/\\+t/g, '\t');
  }

  // 3. Удаление паразитных обратных слешей (\)
  // На конце строк: например "слово\" или "Заключение\"
  str = str.replace(/\\+[ \t]*(?=\r?\n|$)/gm, '');
  // На отдельной пустой строке: строка содержащая только "\"
  str = str.replace(/^[ \t]*\\+[ \t]*$/gm, '');
  // Перед Markdown-заголовками: например "\### Революция"
  str = str.replace(/\\+[ \t]*(#{1,6}\s+)/g, '$1');

  // 4. Изоляция таблиц Markdown пустыми строками
  const lines = str.split('\n');
  const isolatedLines: string[] = [];
  let inTable = false;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const isTableLine = line.trim().startsWith('|');

    if (isTableLine && !inTable) {
      if (isolatedLines.length > 0 && isolatedLines[isolatedLines.length - 1].trim() !== '') {
        isolatedLines.push('');
      }
      inTable = true;
    } else if (!isTableLine && inTable) {
      if (line.trim() !== '') {
        isolatedLines.push('');
      }
      inTable = false;
    }
    isolatedLines.push(line);
  }

  str = isolatedLines.join('\n');

  // 5. Ограничение избыточных пустых строк
  str = str.replace(/\n{3,}/g, '\n\n');

  return str.trim();
}

export function sanitizeTypography(text: string): string {
  if (!text) return text;
  const str = text
    .replace(/ё/g, 'е')
    .replace(/Ё/g, 'Е')
    .replace(/[\u2014\u2013]/g, '-');

  return normalizeMarkdownContent(str);
}

/**
 * Рекурсивно нормализует все строки в объекте ответа ИИ
 */
export function sanitizeOutputTypography<T>(data: T): T {
  if (typeof data === 'string') {
    return sanitizeTypography(data) as unknown as T;
  }
  if (Array.isArray(data)) {
    return data.map((item) => sanitizeOutputTypography(item)) as unknown as T;
  }
  if (data !== null && typeof data === 'object') {
    const sanitizedObj: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(data)) {
      sanitizedObj[key] = sanitizeOutputTypography(value);
    }
    return sanitizedObj as T;
  }
  return data;
}

